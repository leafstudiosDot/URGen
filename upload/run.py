"""CLI to upload a rendered video to YouTube and/or TikTok."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from upload.youtube import upload_video as yt_upload
from upload.tiktok import upload_video as tt_upload


def _load_metadata(path: str | None) -> dict:
	if not path:
		return {}
	try:
		return json.loads(Path(path).read_text(encoding="utf-8"))
	except Exception:
		return {}


def main(argv: list[str] | None = None) -> int:
	parser = argparse.ArgumentParser(description="Upload a video to YouTube/TikTok.")
	parser.add_argument("video", help="Path to the video file.")
	parser.add_argument("--title", default="", help="Title/caption (overrides metadata).")
	parser.add_argument("--description", default="", help="YouTube description (overrides metadata).")
	parser.add_argument("--tags", default="", help="Comma-separated tags (overrides metadata).")
	parser.add_argument("--metadata", default="", help="Path to metadata JSON file generated by the pipeline.")
	parser.add_argument("--platforms", default="youtube,tiktok", help="Comma-separated platforms.")
	parser.add_argument("--privacy-youtube", default="", choices=["", "public", "unlisted", "private"])
	parser.add_argument("--privacy-tiktok", default="")
	args = parser.parse_args(argv if argv is not None else sys.argv[1:])

	meta = _load_metadata(args.metadata)
	title = args.title or meta.get("title") or Path(args.video).stem
	description = args.description or meta.get("description") or title
	tags = [t.strip() for t in args.tags.split(",") if t.strip()] if args.tags else (meta.get("tags") or [title])
	hashtags = meta.get("hashtags") or []
	if hashtags and not args.description:
		description = description + "\n\n" + " ".join(hashtags)
	yt_privacy = args.privacy_youtube or meta.get("youtube_privacy") or "public"
	tt_privacy = args.privacy_tiktok or meta.get("tiktok_privacy") or "PUBLIC_TO_EVERYONE"
	tiktok_title = title
	if hashtags:
		tiktok_title = (title + " " + " ".join(hashtags))[:150]

	platforms = [p.strip().lower() for p in args.platforms.split(",") if p.strip()]

	if "youtube" in platforms:
		try:
			yt_upload(
				args.video,
				title=title,
				description=description,
				tags=tags,
				privacy_status=yt_privacy,
			)
		except Exception as exc:
			print(f"[upload] YouTube failed: {exc}")

	if "tiktok" in platforms:
		try:
			tt_upload(
				args.video,
				title=tiktok_title,
				privacy_level=tt_privacy,
			)
		except Exception as exc:
			print(f"[upload] TikTok failed: {exc}")

	return 0


if __name__ == "__main__":
	raise SystemExit(main())
